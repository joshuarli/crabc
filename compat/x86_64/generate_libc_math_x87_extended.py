#!/usr/bin/env python3
"""Generate the pinned musl AArch64 binary128 extended-math translation."""

import argparse
import re
import subprocess
import tempfile
from pathlib import Path

from generate_libc_math_long_double_completion import (
    COMPILE_FLAGS, EXPECTED_MUSL_TREE_DIGEST, ROOT, architecture_source,
    checked_compiler, finalize_assembly, normalized_tree_digest, transform_assembly,
)

SOURCES = tuple(f"src/math/{name}.c" for name in (
    "acosl", "asinl", "atan2l", "atanl", "ceill", "exp2l", "expl", "expm1l",
    "fabsl", "floorl", "fmodl", "llrintl", "log10l", "log1pl", "log2l",
    "logl", "lrintl", "remainderl", "remquol", "truncl",
))
PRIVATE_SOURCES = ("src/math/__invtrigl.c",)
PRIVATE_SYMBOLS = ("__invtrigl_R", "__pio2_hi", "__pio2_lo")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--arch", choices=("aarch64",), required=True)
    parser.add_argument("--musl-source", type=Path, required=True)
    parser.add_argument("--cc", required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "libc/src/c_abi/x86_64/math_x87_extended_musl_aarch64.S")
    args = parser.parse_args()
    root = args.musl_source.resolve()
    digest = normalized_tree_digest(root)
    if digest != EXPECTED_MUSL_TREE_DIGEST:
        raise SystemExit(f"musl source tree digest mismatch: expected {EXPECTED_MUSL_TREE_DIGEST}, got {digest}")
    compiler = checked_compiler(args.cc, arch=args.arch)
    includes = [f"-I{root / path}" for path in (
        "src/math", "src/internal", "src/include", "arch/aarch64", "arch/generic", "include",
    )]
    notices = []
    for source in SOURCES + PRIVATE_SOURCES:
        for notice in re.findall(r"/\*.*?\*/", (root / source).read_text(), re.DOTALL):
            if "Copyright" in notice and notice not in notices:
                notices.append(notice)
    blocks = ["/* Fixed musl 1.2.6 AArch64 binary128 extended-math translation.",
              " * Generated by compat/x86_64/generate_libc_math_x87_extended.py.",
              " * Musl-authored portions retain musl's MIT license; see compat/upstreams.toml.",
              " */", *notices]
    with tempfile.TemporaryDirectory(prefix="crabc-math-x87-extended-") as temp:
        for index, source in enumerate(SOURCES + PRIVATE_SOURCES):
            assembly = Path(temp) / f"{index}.s"
            input_path = architecture_source(root, source, args.arch)
            subprocess.run([compiler, *COMPILE_FLAGS, *includes, "-S", str(input_path), "-o", str(assembly)], check=True)
            blocks.append(f"\n/* musl-1.2.6/{input_path.relative_to(root)} */")
            text = transform_assembly(source, assembly.read_text())
            for symbol in PRIVATE_SYMBOLS:
                name = "crabc_aarch64_extended_" + symbol
                text = re.sub(r"(?<![A-Za-z0-9_.$])" + symbol + r"(?![A-Za-z0-9_.$])", name, text)
                text = re.sub(r"(?m)^(\s*)\.(?:global|globl)\s+" + name + r"\s*$", r"\1.local " + name, text)
            blocks.append(text)
    blocks.append('\n.section .note.GNU-stack,"",@progbits\n')
    output = finalize_assembly("\n".join(blocks), args.arch)
    args.output.write_text(output)
    print(f"wrote {args.output} ({output.count(chr(10))} lines)")


if __name__ == "__main__":
    main()
